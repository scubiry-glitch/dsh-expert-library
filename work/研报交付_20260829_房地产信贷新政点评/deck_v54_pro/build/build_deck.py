def rewrite_app_xml(path, n_slides):
    """重写 docProps/app.xml：写入真实 Slides 统计（修复 docprops_slide_count_mismatch）。"""
    import zipfile, shutil, re
    tmp = path + ".tmp"
    with zipfile.ZipFile(path, "r") as zin, \
         zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED) as zout:
        for item in zin.infolist():
            data = zin.read(item.filename)
            if item.filename == "docProps/app.xml":
                xml = data.decode("utf-8")
                if "<Slides>" in xml:
                    xml = re.sub(r"<Slides>\d+</Slides>", f"<Slides>{n_slides}</Slides>", xml)
                else:
                    xml = xml.replace("</Properties>",
                                      f"<Slides>{n_slides}</Slides></Properties>")
                data = xml.encode("utf-8")
            zout.writestr(item, data)
    shutil.move(tmp, path)


