#!/bin/bash
# G1 文字门 grep 循环脚本 v2（全门重跑）— 研报主文_信用卡对标_20260830.md（203 行版，含第四/五章）
# 用法: bash 门禁检查_g1_grep_v2.sh 2>&1 | tee 门禁检查_g1_grep_result_v2.txt
# 规则依据: zhijian-report-craft SKILL.md §1(去过程痕迹/金句纪律) §3 G1(禁例 0 命中、应有项 100% 在位)
F="研报主文_信用卡对标_20260830.md"
[ -f "$F" ] || { echo "ERR: $F 不存在"; exit 1; }

echo "======================================================"
echo "[A] 禁例 token 扫描（过程痕迹，期望 0 命中）"
echo "======================================================"
TOKENS=("版本" "修订" "评审" "专家" "轮次" "第[0-9一二三四五六七八九十]*轮" "初稿" "终稿" "草稿" "一一" "队长" "守门员" "门禁" "检查记录" "修改记录" "v[0-9]" "V[0-9]" "渲染" "迭代" "会议纪要" "审批记录" "待核" "草拟")
for t in "${TOKENS[@]}"; do
  hits=$(grep -nE "$t" "$F" || true)
  if [ -n "$hits" ]; then
    echo "── 命中「$t」:"
    echo "$hits" | sed 's/^/    /'
  else
    echo "── 「$t」: 0 命中 ✓"
  fi
done

echo ""
echo "======================================================"
echo "[B] 模糊修饰词扫描（约/近/左右/大概/大约，逐条人工判定是否替代精确数字）"
echo "======================================================"
for w in "约" "近" "左右" "大概" "大约" "上下"; do
  echo "── 「$w」 $(grep -o "$w" "$F" | wc -l) 处:"
  grep -n "$w" "$F" | sed 's/^/    /'
done

echo ""
echo "======================================================"
echo "[C] 应有项检查（5 章版，期望全部在位）"
echo "======================================================"
for pat in "卷首速览" "章眼金句" "总纲金句" "收束金句" "角色对照卡" "事实依据" "推论与数据" "机会与风险" "来源披露" "待补"; do
  n=$(grep -c "$pat" "$F")
  echo "── 「$pat」: $n 处"
done

echo ""
echo "======================================================"
echo "[D] 章节五件套逐章核验"
echo "======================================================"
grep -nE "^## |^### " "$F" | sed 's/^/    /'

echo ""
echo "======================================================"
echo "[E] 引用格式抽查（Wind/数据底座/新来源引用标注）"
echo "======================================================"
grep -nE "Wind EDB|M0001428|M0251917|官方披露|内部披露|branch_product_metrics|jsbank_new_pricing_weekly|吉利|比亚迪|融合易贷|建行|中信" "$F" | sed 's/^/    /'

echo ""
echo "======================================================"
echo "[F] 队长点名锚点存在性扫描（4.1-4.7% / 1.39pct / 143倍 / 877元 / 26.7亿 / 1.3亿 / 11.3 / 18.1 / 29亿 / 2.47% / 1.53%）"
echo "======================================================"
for p in "4.1" "4.7" "1.39" "143" "877" "26.7" "1.3 亿" "11.3" "18.1" "29 亿" "2.47" "1.53" "mix-shift" "23%" "10%"; do
  echo "── 「$p」: $(grep -o "$p" "$F" | wc -l) 处"
done

echo ""
echo "G1 grep 循环 v2 完成。"
